import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { activation, dispatchPlanned, plannedQueue, scheduledClaim } from '../src/plannedDispatch.js';
import { Database } from '../src/ofocus/database.js';
import { newTask } from '../src/ofocus/model.js';
import { nativeSnapshots } from '../src/snapshot.js';
import { key, save } from '../src/monitor/store.js';

test('planned AFK dispatch excludes backlog, rechecks eligibility and records confirmed outcomes', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'of-planned-'));
  t.after(() => fs.rm(root, {recursive:true, force:true}));
  const since = 1000, planned = new Date(2000).toISOString();
  const project = {...newTask('project'), isProject:true, projectStatus:'active'};
  const action = {...newTask('action'), planned, parentId:'project', primaryTagId:'afk'};
  const db = Database.fromJSON({ tasks:[['project', project],['action',action]], folders:[], tags:[['afk',{id:'afk',name:'🤖 AFK'}]], tagJoins:[], settings:[] });
  const state = {available:true, completed:false, dropped:false, ofStatus:'Next', effectiveDue:null, effectiveDefer:null};
  nativeSnapshots.set(db,{observedAt:planned, states:new Map([['action',state]])});
  const refresh = () => plannedQueue(db,root,'project',since,3000);
  assert.equal(await activation(root,'project',false),null);
  assert.deepEqual(await fs.readdir(root),[]);
  assert.equal(await activation(root,'project',true,()=>since),since);
  assert.equal(await activation(root,'project',true,()=>4000),since);
  assert.equal((await plannedQueue(db,root,'project',since,1500))[0].reason,'future');
  action.planned = new Date(500).toISOString();
  assert.equal((await refresh())[0].reason,'before-activation');
  action.planned = planned;
  state.available = false;
  assert.equal((await refresh())[0].reason,'unavailable');
  state.available = true;
  const [candidate] = await refresh();
  assert.equal(candidate.reason,'ready');
  action.planned = new Date(4000).toISOString();
  const args = {root, project:'project', candidate, refresh};
  assert.equal((await dispatchPlanned({...args,launch:async()=>assert.fail()})).status,'skipped');
  action.planned = planned;
  let launches = 0;
  const launch = async (assignment: any) => {
    launches++;
    const input = {...assignment,event:'start'};
    const task = {planned, tags:['🤖 AFK'], statusSource:'omnifocus-sqlite'};
    assert.deepEqual(await scheduledClaim(root,input,task),{planned,project:'project'});
    await assert.rejects(scheduledClaim(root,input,{...task,planned:new Date(5000).toISOString()}),/changed/);
    await assert.rejects(scheduledClaim(root,input,{...task,tags:['AFK','⏸ 等待']}),/eligible/);
    await save(path.join(root,'local-ownership', key('action')+'.json'), {...assignment,event:'done'});
  };
  const results = await Promise.all([dispatchPlanned({...args,launch}),dispatchPlanned({...args,launch})]);
  assert.deepEqual(results.map(r=>r.status).sort(),['done','skipped']);
  assert.equal(launches,1);
  assert.equal((await refresh())[0].reason,'done');
  action.planned = new Date(2100).toISOString();
  const [next] = await refresh();
  const failed = await dispatchPlanned({...args,candidate:next, launch:async()=>{throw Error('worker lost');}});
  assert.equal(failed.status,'needs-inspection');
  assert.equal((await refresh())[0].reason,'needs-inspection');
});
